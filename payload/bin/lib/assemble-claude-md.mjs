// Assembles the curated ~/.claude/CLAUDE.md from per-profile fragments in payload/claude-md/.
// Self-contained (only node:* imports) so setup.mjs can import it directly.
//
// Fragment naming: `NN-stem.md` (shared) and/or `NN-stem.<profile>.md` (per-profile override,
// profile in full|base|lite). A profile's assembled output picks, per stem, the override file
// for that profile if one exists, else the shared file gated by its optional frontmatter
// `profiles: [..]` list (absent list = applies to all profiles). Sections are emitted in NN
// order. Output always starts with the CURATED:NOEDIT marker (installer invariant) followed by
// a GENERATED header pointing back at the fragment source - never hand-edit the assembled file.
import { readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";

const HEADER =
  "<!-- CURATED:NOEDIT -->\n" +
  "<!-- GENERATED by assemble-claude-md.mjs — edit fragments in payload/claude-md/, not this file. -->\n";

export function parseFragment(text) {
  // Normalize line endings FIRST: the repo has core.autocrlf=true, so a fresh Windows checkout
  // materializes payload/claude-md/*.md with CRLF even though they're authored/stored as LF.
  // The frontmatter/body regexes below anchor on bare \n and silently fail to match \r\n,
  // which would leak the raw "---\r\nprofiles: [...]\r\n---" block into the assembled output
  // and break profile gating (see .gitattributes for the belt-and-suspenders EOL pin).
  text = text.replace(/\r\n/g, "\n").replace(/\r/g, "\n");
  const m = text.match(/^---\n([\s\S]*?)\n---\n?/);
  if (!m) return { profiles: null, body: text.replace(/^\n+/, "") };
  const body = text.slice(m[0].length).replace(/^\n+/, "");
  const pm = m[1].match(/^profiles:\s*\[(.*)\]\s*$/m);
  const profiles = pm ? pm[1].split(",").map((s) => s.trim()).filter(Boolean) : null;
  return { profiles, body };
}

export function assembleClaudeMd(fragmentsDir, profile) {
  const files = readdirSync(fragmentsDir).filter((f) => /^\d\d-.*\.md$/.test(f));
  const bySection = new Map(); // stem -> { shared, overrides:Map<profile,file> }
  for (const f of files) {
    const mo = f.match(/^(\d\d-[a-z0-9-]+?)(?:\.(full|base|lite))?\.md$/);
    if (!mo) continue;
    const [, stem, ovr] = mo;
    if (!bySection.has(stem)) bySection.set(stem, { shared: null, overrides: new Map() });
    const rec = bySection.get(stem);
    if (ovr) rec.overrides.set(ovr, f); else rec.shared = f;
  }
  const parts = [];
  for (const stem of [...bySection.keys()].sort()) {
    const rec = bySection.get(stem);
    const overrideFile = rec.overrides.get(profile);
    const file = overrideFile || rec.shared;
    if (!file) continue;
    const { profiles, body } = parseFragment(readFileSync(join(fragmentsDir, file), "utf8"));
    if (!overrideFile && profiles && !profiles.includes(profile)) continue; // shared gated by profiles list
    parts.push(body.trimEnd());
  }
  return HEADER + "\n" + parts.join("\n\n") + "\n";
}
